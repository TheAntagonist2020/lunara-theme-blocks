#!/usr/bin/env node
'use strict';

// Development-only: node tests/tools/build-shell-css.cjs [--check]
// The original shell remains the canonical input and the runtime fallback.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const zlib = require('node:zlib');
const postcss = require('postcss');
const selectorParser = require('postcss-selector-parser');

const sourcePath = path.resolve(__dirname, '../../assets/css/lunara-shell.css');
const outputPath = path.resolve(__dirname, '../../assets/css/lunara-shell-non-portal.css');
const portalClass = 'lunara-oscars-portal-page';

function onlyPortalSelectors(selector) {
    const parsed = selectorParser().astSync(selector);
    return parsed.nodes.length > 0 && parsed.nodes.every(branch => {
        const nodes = branch.nodes.filter(node => node.type !== 'comment');
        const first = nodes[0];
        if (!first || first.type !== 'tag' || first.value.toLowerCase() !== 'body' || first.namespace !== undefined) {
            return false;
        }
        // Inspect only the body's own compound. A class inside :not(), :is(),
        // an attribute value, or a descendant is not a positive body anchor.
        for (const node of nodes.slice(1)) {
            if (node.type === 'combinator') break;
            if (node.type === 'class' && node.value === portalClass) return true;
        }
        return false;
    });
}

function buildShell(source) {
    const parsed = postcss.parse(source, { from: sourcePath });
    const ranges = [];
    parsed.walkRules(rule => {
        // Keep future CSS nesting and unfamiliar at-rules conservative.
        for (let parent = rule.parent; parent && parent.type !== 'root'; parent = parent.parent) {
            if (parent.type !== 'atrule' || !['media', 'supports', 'layer', 'container'].includes(parent.name.toLowerCase())) return;
        }
        if (!onlyPortalSelectors(rule.selector)) return;
        ranges.push([rule.source.start.offset, rule.source.end.offset]);
    });

    // Splice exact source ranges without rewriting selectors, declarations,
    // comments, or media wrappers. Clean only indentation left on empty lines
    // and excess EOF blank lines after the removed rules.
    let cursor = 0;
    let retained = '';
    for (const [start, end] of ranges) {
        if (start < cursor || end <= start) throw new Error('Overlapping CSS rule ranges');
        retained += source.slice(cursor, start);
        cursor = end;
    }
    retained += source.slice(cursor);
    retained = retained.replace(/^[\t ]+(?=\r?$)/gm, '').replace(/(\r?\n)(?:\r?\n)+$/, '$1');
    const hash = crypto.createHash('sha256').update(source).digest('hex');
    const banner = '/* Generated by tests/tools/build-shell-css.cjs; edit lunara-shell.css instead.\n' +
        ` * Source SHA-256: ${hash}\n */\n`;
    return { css: banner + retained, retained, ranges };
}

function checkArtifact(source, artifact) {
    const expected = buildShell(source).css;
    if (artifact !== expected) {
        throw new Error('Stale non-portal shell. Run node tests/tools/build-shell-css.cjs');
    }
}

if (require.main === module) {
    const args = process.argv.slice(2);
    if (args.length > 1 || (args.length === 1 && args[0] !== '--check')) {
        throw new Error('Usage: node tests/tools/build-shell-css.cjs [--check]');
    }
    const source = fs.readFileSync(sourcePath, 'utf8');
    const built = buildShell(source);
    if (args[0] === '--check') {
        checkArtifact(source, fs.readFileSync(outputPath, 'utf8'));
    } else {
        fs.writeFileSync(outputPath, built.css);
    }
    console.log(JSON.stringify({
        mode: args[0] === '--check' ? 'check' : 'build',
        removedRules: built.ranges.length,
        sourceBytes: Buffer.byteLength(source),
        outputBytes: Buffer.byteLength(built.css),
        rawSaved: Buffer.byteLength(source) - Buffer.byteLength(built.css),
        gzipSaved: zlib.gzipSync(source).length - zlib.gzipSync(built.css).length,
    }));
}

module.exports = { buildShell, checkArtifact, onlyPortalSelectors, sourcePath, outputPath };
